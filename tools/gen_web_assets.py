#!/usr/bin/env python3
"""Embed vendored web assets (Leaflet) into web_assets.c.

The dashboard loads its map library from the sniffer itself, so it works
offline. Run from anywhere after changing vendor/: python3 tools/gen_web_assets.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEAFLET = "vendor/leaflet-1.9.4"
# (URL path, file, content type)
ASSETS = [
    ("/vendor/leaflet/leaflet.js", f"{LEAFLET}/leaflet.js", "application/javascript; charset=utf-8"),
    ("/vendor/leaflet/leaflet.css", f"{LEAFLET}/leaflet.css", "text/css; charset=utf-8"),
] + [
    (f"/vendor/leaflet/images/{n}", f"{LEAFLET}/images/{n}", "image/png")
    for n in ("layers.png", "layers-2x.png", "marker-icon.png", "marker-icon-2x.png", "marker-shadow.png")
]


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    return "\n".join(lines)


def main():
    out = ["/* Generated by tools/gen_web_assets.py from vendor/. Do not edit. */",
           '#include "web_assets.h"', ""]
    table = []
    for i, (path, rel, ctype) in enumerate(ASSETS):
        with open(os.path.join(ROOT, rel), "rb") as f:
            data = f.read()
        out.append(f"/* {rel} */")
        out.append(f"static const unsigned char asset_{i}[{len(data)}] = {{")
        out.append(c_bytes(data))
        out.append("};")
        table.append(f'    {{ "{path}", "{ctype}", asset_{i}, sizeof(asset_{i}) }},')
    out.append("")
    out.append("const web_asset_t WEB_ASSETS[] = {")
    out += table
    out.append("    { 0, 0, 0, 0 }")
    out.append("};")
    with open(os.path.join(ROOT, "web_assets.c"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
